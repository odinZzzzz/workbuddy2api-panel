// faceNames 给模型看的可用名单（按类别串好，避免它瞎猜名字）。
func faceNames() string {
	groups := [][]string{
		{"微笑", "呲牙", "偷笑", "可爱", "调皮", "得意", "酷", "憨笑"},
		{"白眼", "傲慢", "鄙视", "抠鼻", "坏笑", "阴险", "折磨", "敲打"},
		{"发怒", "咒骂", "抓狂", "撇嘴", "闭嘴", "嘘", "敲打", "菜刀"},
		{"大哭", "流泪", "快哭了", "委屈", "可怜", "难过", "心碎", "衰"},
		{"害羞", "亲亲", "爱你", "爱心", "示爱", "飞吻", "玫瑰", "拥抱"},
		{"冷汗", "擦汗", "流汗", "晕", "惊恐", "吓", "发呆", "疑问"},
		{"鼓掌", "强", "胜利", "抱拳", "握手", "OK", "NO", "挥手"},
	}
	seen := map[string]bool{}
	var all []string
	for _, g := range groups {
		for _, n := range g {
			if !seen[n] {
				seen[n] = true
				all = append(all, n)
			}
		}
	}
	return strings.Join(all, "、")
}

// resolveFace 把名字或数字解析成 QQ 表情 id。
func resolveFace(name string) (string, error) {
	n := strings.TrimSpace(name)
	if n == "" {
		return "", fmt.Errorf("没说发哪个表情")
	}
	if id, err := strconv.Atoi(n); err == nil && id >= 0 && id <= 200 {
		return strconv.Itoa(id), nil
	}
	if id, ok := qqFaces[n]; ok {
		return id, nil
	}
	// 容错：去掉「表情」「脸」这类后缀再试
	for _, suf := range []string{"表情", "脸", "脸脸"} {
		if v, ok := qqFaces[strings.TrimSuffix(n, suf)]; ok {
			return v, nil
		}
	}
	return "", fmt.Errorf("没有叫「%s」的 QQ 表情，可用的有：%s", n, faceNames())
}
